"""Turn the fit results (../results/*.json) into ../PROTOTYPE.md. Numbers only come from the files.

Run: python write_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE.parent / "results"
TYPES = {"lr_sb_best": "state-based", "lr_ns_best": "non-state", "lr_os_best": "one-sided"}
DOLLS = ["cell", "ring 1", "ring 2", "rest of country", "rest of map"]
MEMORY_CEILING = 600.0


def _knob_table(fit: dict) -> list[str]:
    rows = ["| doll | weight | memory (months) |", "|---|---|---|"]
    for name, w, m in zip(DOLLS, fit["weight"], fit["memory"]):
        flag = " (at the ceiling)" if m >= MEMORY_CEILING * 0.99 else ""
        rows.append(f"| {name} | {w:.4g} | {m:.1f}{flag} |")
    return rows


def _stability(r: dict) -> list[str]:
    if "leave_one_cutoff_out" not in r:
        return ["Not run (`--stability` not set)."]
    rows = ["| cutoff left out | " + " | ".join(f"memory {d}" for d in DOLLS)
            + " | weight ring 1 | weight ring 2 | weight country | weight map |",
            "|---" * 10 + "|"]
    for s in r["leave_one_cutoff_out"]:
        rows.append(f"| {s['left_out']} | " + " | ".join(f"{m:.1f}" for m in s["memory"])
                    + " | " + " | ".join(f"{w:.3g}" for w in s["weight"][1:]) + " |")
    return rows


def main() -> None:
    out = ["# Matryoshka prototype: fitted knobs on real data", "",
           "Generated by `prototype/write_report.py` from `results/*.json` "
           "(`prototype/fit_knobs.py`). ADR-024; issue #127.", "",
           "Data: the calibration input pull (pgm `land`, 64,818 cells), months 121–456 only "
           "(nothing after the last training month). Backtest cutoffs 384, 396, 408, 420; "
           "forecast months 1–36 after each. Score: mean log probability of the observed size "
           "class (higher is better).", ""]
    for target, label in TYPES.items():
        path = RESULTS / f"{target}.json"
        if not path.exists():
            out += [f"## {label} (`{target}`)", "", "No result yet.", ""]
            continue
        r = json.loads(path.read_text())
        f, ref = r["fit"], r["references"]
        w = f["weight"]
        out += [f"## {label} (`{target}`)", "",
                f"**Fitted score {f['score']:.5f}**, against {ref['conflictology_36m']['score']:.5f} "
                f"for conflictology (36-month window, cell only) and "
                f"{ref['cell_all_history']['score']:.5f} for the cell's whole history. "
                f"Starting values scored {r['start_score']:.5f}.", "",
                f"Forecasts that gave the observed class essentially zero probability "
                f"(< 1e-12, floored to keep the log finite): **{f['floored']:,}** for Matryoshka, "
                f"{ref['conflictology_36m']['floored']:,} for conflictology. Conflictology's score "
                f"is dominated by these, so its gap to Matryoshka depends on the floor; the counts "
                f"are the robust comparison.", "",
                *_knob_table(f), "",
                f"Ring ratios: ring 1 / cell = {w[1] / w[0]:.3g}, ring 2 / ring 1 = "
                f"{w[2] / w[1]:.3g} (Currents of Conflict suggests about 0.4 per ring).", "",
                f"Fit: {f['evaluations']} score evaluations, {f['seconds']} s, converged: "
                f"{f['converged']} ({f['message']}).", "",
                "Size classes seen in the history (cell-months): "
                + ", ".join(f"{k}: {v:,}" for k, v in r["class_counts_in_history"].items()), "",
                "**Stability (each cutoff left out in turn):**", "", *_stability(r), "",
                f"Timing: doll counts {r['timing_seconds']['doll_counts']} s, first score "
                f"evaluation {r['timing_seconds']['first_score_evaluation']} s; peak memory "
                f"{r['peak_rss_gib']} GiB.", ""]
    (HERE.parent / "PROTOTYPE.md").write_text("\n".join(out))
    print("wrote", HERE.parent / "PROTOTYPE.md")


if __name__ == "__main__":
    main()
